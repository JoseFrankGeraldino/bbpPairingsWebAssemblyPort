@dataclass
class Case:
    name: str
    trf: bytes
    rounds: int
    team: bool = False


@dataclass
class ErrorCase:
    name: str
    args: list[str]
    trf: Optional[bytes]
    exit_code: int
    stderr_contains: str
    stdout: Optional[str] = None


def last_round(trf: bytes) -> int:
    """The highest round number that has a result column in a 001 record."""
    rounds = 0
    for line in trf.decode("latin-1").replace("\r", "\n").split("\n"):
        if line.startswith("001"):
            rounds = max(rounds, max(0, (len(line.rstrip()) - 89) // 10))
    return rounds


def run(args: list[str], cwd: Path) -> tuple[int, bytes, bytes]:
    result = subprocess.run(
        args,
        cwd=cwd,
        capture_output=True,
        timeout=TIMEOUT_SECONDS,
    )
    return result.returncode, result.stdout, result.stderr


def generate(engine: Path, config: Optional[Path], seed: int, work: Path) -> bytes:
    # The engine resolves -o relative to the configuration file, so the file
    # is copied into the work directory and named relatively (as in
    # run_tests.py); a stale output must never be read back.
    output = work / "gen.trf"
    if output.exists():
        output.unlink()
    args = [str(engine), "--dutch", "-g"]
    if config is not None:
        (work / config.name).write_bytes(config.read_bytes())
        args.append(config.name)
    args += ["-o", "gen.trf", "-s", str(seed)]
    rc, stdout, stderr = run(args, work)
    # The engine ends lines with CR; any player record will do as a sanity
    # check that a tournament was written.
    if rc != 0 or not output.exists() or b"001 " not in output.read_bytes():
        raise RuntimeError(
            "generator failed (%d) for %s seed %d: %s"
            % (rc, config, seed, (stdout + stderr).decode(errors="replace"))
        )
    return (work / "gen.trf").read_bytes()


def collect_cases(engine: Path, count: int, work: Path) -> list[Case]:
    cases = []
    for path in sorted((FIXTURES / "samples").glob("*.trf")):
        data = path.read_bytes()
        cases.append(Case("samples/" + path.stem, data, last_round(data)))
    for name, data in tiebreak_inputs.feature_inputs():
        cases.append(Case("features/" + name, data, last_round(data)))
    sources: list[tuple[str, Optional[Path]]] = [("default", None)]
    sources += [
        (path.stem, path) for path in sorted((FIXTURES / "generator").glob("*.cfg"))
    ]
    seen: dict[bytes, str] = {}
    for label, config in sources:
        for seed in range(1, count + 1):
            data = generate(engine, config, seed, work)
            name = "generated/%s-seed-%04d" % (label, seed)
            # Every source and seed must give its own tournament; a repeat
            # means the generator was not driven as intended.
            if data in seen:
                raise RuntimeError("%s is identical to %s" % (name, seen[data]))
            seen[data] = name
            cases.append(Case(name, data, last_round(data)))
    teams = tiebreak_team_inputs.team_feature_inputs()
    teams += tiebreak_team_inputs.generated_team_inputs(count)
    for stem, data in teams:
        name = "teams/" + stem
        if data in seen:
            raise RuntimeError("%s is identical to %s" % (name, seen[data]))
        seen[data] = name
        cases.append(Case(name, data, last_round(data), team=True))
    return cases


def compare(
    case: Case, variant: Variant, tool: Path, gacrux: Path
) -> Optional[str]:
    with tempfile.TemporaryDirectory(prefix="tbcmp-") as directory:
        work = Path(directory)
        (work / "input.trf").write_bytes(case.trf)
        args = list(variant.args)
        if variant.intermediate:
            if case.rounds < 2:
                return None
            args = ["-n", str(case.rounds - 1)] + args
        reference = run(
            [
                sys.executable,
                str(gacrux / "tiebreakchecker.py"),
                "-i",
                "input.trf",
                "-dT",
                *args,
            ],
            work,
        )
        ours = run([str(tool), "-i", "input.trf", "-d", "T", *args], work)
    stem = case.name.split("/", 1)[1]
    if stem in UNSUPPORTED_INPUTS:
        if reference[0] == 0 or ours[0] == 0:
            pass  # fall through: compare as usual, the reason may be gone
        else:
            return None
    if (
        reference[1].startswith(REFERENCE_PROGRAM_ERROR)
        and ours[0] == 3
        and any(message in ours[2] for message in KNOWN_REFERENCE_DEFECTS)
    ):
        return KNOWN_DEFECT
    # Deliberate difference: a failed -c check exits 1 here, while
    # tiebreakchecker exits 0 and reports it only in its JSON status.
    expected_exit = reference[0]
    if expected_exit == 0 and b"Check: False" in reference[1]:
        expected_exit = 1
    if expected_exit == ours[0] and reference[1] == ours[1]:
        return None
    return (
        "exit gacrux %d, ours %d\n--- gacrux stdout\n%s\n--- ours stdout\n%s"
        "\n--- gacrux stderr\n%s\n--- ours stderr\n%s"
        % (
            reference[0],
            ours[0],
            reference[1].decode("latin-1")[:3000],
            ours[1].decode("latin-1")[:3000],
            reference[2].decode("latin-1")[-1500:],
            ours[2].decode("latin-1")[-1500:],
        )
    )



#!/usr/bin/env python3
"""Differential test: our tie-break tool against FIDE's Gacrux.

Part of bbpPairingsWebAssemblyPort (MIT). Python 3 standard library only.

Every input is run through Gacrux's tiebreakchecker (the reference,
https://github.com/OttoMilvang/TieBreakServer, pinned by commit) and through
our C++ port with the same arguments. Standard output and exit status must be
identical byte for byte; any difference fails the run.

Inputs:
  samples    every TRF in tests/fixtures/samples
  features   synthetic individual tournaments (tests/tiebreak_inputs.py)
  generated  tournaments generated by the pinned engine (--engine) with fixed
             seeds, from the default generator and every configuration in
             tests/fixtures/generator (count per source: --count)
  teams      team tournaments from tests/tiebreak_team_inputs.py: one per
             forced feature and --count generated with fixed seeds

Each individual input runs in several variants (VARIANTS below): all
mandatory individual tie-breaks of the FIDE list, the same list for an
intermediate round, as a pre-determined (round robin) and as a Swiss
tournament, with a rating for unrated players, the file's own rank order, a
checked and a rank-sorted standing. Team inputs run TEAM_VARIANTS, built the
same way on the team part of the list.

Error behaviour (exit codes, messages) of our tool is covered by the inline
cases in ERROR_CASES, which do not involve Gacrux.
"""


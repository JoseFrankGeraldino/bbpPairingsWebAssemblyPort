def run_error_case(case: ErrorCase, tool: Path) -> Optional[str]:
    with tempfile.TemporaryDirectory(prefix="tberr-") as directory:
        work = Path(directory)
        if case.trf is not None:
            (work / "input.trf").write_bytes(case.trf)
        stdin = case.trf if "-" in case.args else None
        result = subprocess.run(
            [str(tool), *case.args],
            cwd=work,
            input=stdin,
            capture_output=True,
            timeout=TIMEOUT_SECONDS,
        )
    stderr = result.stderr.decode(errors="replace")
    stdout = result.stdout.decode(errors="replace")
    if result.returncode != case.exit_code:
        return "exit %d, expected %d (stderr: %s)" % (
            result.returncode, case.exit_code, stderr.strip()
        )
    if case.stderr_contains not in stderr:
        return "stderr %r does not contain %r" % (stderr, case.stderr_contains)
    if case.stdout is not None and case.stdout not in stdout:
        return "stdout %r does not contain %r" % (stdout, case.stdout)
    return None


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--tool", required=True, type=Path)
    parser.add_argument("--gacrux", required=True, type=Path,
                        help="directory holding tiebreakchecker.py")
    parser.add_argument("--engine", required=True, type=Path,
                        help="bbpPairings binary used to generate tournaments")
    parser.add_argument(
        "--count",
        type=int,
        default=int(os.environ.get("BBP_TIEBREAK_COUNT", "20")),
        help="generated tournaments per source (default 20)",
    )
    parser.add_argument("--jobs", type=int, default=os.cpu_count() or 2)
    args = parser.parse_args()
    tool = args.tool.resolve()
    gacrux = args.gacrux.resolve()
    if not (gacrux / "tiebreakchecker.py").is_file():
        print("Gacrux not found at %s" % gacrux, file=sys.stderr)
        return 2

    failures = []
    for case in error_cases():
        error = run_error_case(case, tool)
        if error:
            failures.append(("errors/" + case.name, error))

    with tempfile.TemporaryDirectory(prefix="tbgen-") as directory:
        cases = collect_cases(args.engine.resolve(), args.count, Path(directory))

    jobs = [
        (case, variant)
        for case in cases
        for variant in (TEAM_VARIANTS if case.team else VARIANTS)
    ]
    with concurrent.futures.ThreadPoolExecutor(max_workers=args.jobs) as pool:
        results = list(
            pool.map(lambda job: (job, compare(job[0], job[1], tool, gacrux)), jobs)
        )
    defects = []
    for (case, variant), error in results:
        if error == KNOWN_DEFECT:
            defects.append("%s [%s]" % (case.name, variant.name))
        elif error:
            failures.append(("%s [%s]" % (case.name, variant.name), error))

    for name, error in failures:
        print("FAIL %s\n%s\n" % (name, error))
    for name in defects:
        print("KNOWN REFERENCE DEFECT %s (both refused)" % name)
    total = len(jobs) + len(error_cases())
    team_cases = sum(1 for case in cases if case.team)
    print(
        "tie-break comparison: %d individual inputs x %d variants, %d team"
        " inputs x %d variants, %d error cases, %d known reference defects,"
        " %d failed"
        % (len(cases) - team_cases, len(VARIANTS), team_cases,
           len(TEAM_VARIANTS), len(error_cases()), len(defects),
           len(failures))
    )
    return 1 if failures else 0 if total else 2



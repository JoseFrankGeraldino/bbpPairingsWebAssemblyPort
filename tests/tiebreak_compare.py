def small_team_trf(extra: tuple[str, ...] = (), size: int = 2) -> bytes:
    """A consistent four-team event, two boards by default, with extra records."""
    options = tiebreak_team_inputs.Options(
        teams=4, size=size, reserves=0, round_robin=False, double=False,
        rounds=3, extra=list(extra))
    return tiebreak_team_inputs.team_tournament(1, options)


def first_opponent(trf: bytes) -> int:
    """The team that team 1 met in round 1 of small_team_trf()."""
    for line in trf.decode("latin-1").splitlines():
        if line.startswith("001    1"):
            return (int(line[91:95]) - 1) // 2 + 1
    raise RuntimeError("player 1 not found")



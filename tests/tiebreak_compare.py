#!/usr/bin/env python3
"""Differential test: our tie-break tool against FIDE's Gacrux.

Part of bbpPairingsWebAssemblyPort (MIT). Python 3 standard library only.

Every input is run through Gacrux's tiebreakchecker (the reference,
https://github.com/OttoMilvang/TieBreakServer, pinned by commit) and through
our C++ port with the same arguments. Standard output and exit status must be
identical byte for byte; any difference fails the run.

Inputs:
  samples    every TRF in tests/fixtures/samples
  generated  tournaments generated by the pinned engine (--engine) with fixed
             seeds, from the default generator and every configuration in
             tests/fixtures/generator (count per source: --count)

Each input runs in several variants (VARIANTS below): all mandatory individual
tie-breaks of the FIDE list, the same list for an intermediate round, as a
pre-determined (round robin) and as a Swiss tournament, with a rating for
unrated players, the file's own rank order, a checked and a rank-sorted
standing.

Error behaviour (exit codes, messages) of our tool is covered by the inline
cases in ERROR_CASES, which do not involve Gacrux.
"""

from __future__ import annotations

import argparse
import concurrent.futures
import os
import subprocess
import sys
import tempfile
from dataclasses import dataclass
from pathlib import Path
from typing import Optional

ROOT = Path(__file__).resolve().parents[1]
FIXTURES = ROOT / "tests" / "fixtures"
TIMEOUT_SECONDS = 300

sys.path.insert(0, str(ROOT / "tests"))
import tiebreak_inputs  # noqa: E402  (tests/tiebreak_inputs.py)

# The individual tie-breaks of FIDE's "Mandatory Tie-Breaks" list (TRF-26),
# with every modifier and option the list requires. KS/Lx is required for
# "any reasonable value"; three are tested.
MANDATORY_INDIVIDUAL = (
    "PTS DE DE/P WIN WON BPG BWG REP PS PS/C1 PS/C2"
    " BH BH/C1 BH/C2 BH/M1 BH/M2 BH/P BH/C1/P BH/C2/P BH/M1/P BH/M2/P"
    " FB FB/C1 FB/C2 FB/M1 FB/M2 FB/P FB/C1/P FB/C2/P FB/M1/P FB/M2/P"
    " SB SB/C1 SB/C2 SB/P SB/C1/P SB/C2/P"
    " AOB AOB/F KS KS/L+1 KS/L-2 KS/L60"
    " ARO ARO/C1 ARO/C2 ARO/M1 ARO/M2 TPR PTP APRO APPO"
).split()

# A common real-world order, where direct encounter follows other criteria.
TYPICAL = "PTS BH/C1 BH SB DE WIN BPG ARO".split()

# Helper values, modifiers outside the mandatory list (rules versions, the
# 2022 cut rule, Koya limits with a fraction, options that individual events
# ignore) and an unknown name, which both tools score as NUL.
HELPERS = (
    "PTS SNO TPN RANK RTG NUM RIP VUR GE COD RTNG ABH AFB XYZ BH@23"
    " BH/V0 BH/V2024 BH/V1 SB/N ARO/V0/C1 ARO/V2022/M1 KS/K3 KS/L+1.5 KS/L-1"
    " BH/D BH/X FB/F BH/R PS/S DE/S"
).split()

# Inputs our tool rejects on purpose (name -> reason); both tools must fail.
UNSUPPORTED_INPUTS = {
    "synthetic-trf2026-team-swiss": "team tournaments (milestone 2)",
}


@dataclass(frozen=True)
class Variant:
    name: str
    args: tuple[str, ...]
    intermediate: bool = False  # add -n <last round - 1>


VARIANTS = (
    Variant("mandatory", ("-t", *MANDATORY_INDIVIDUAL)),
    Variant("intermediate", ("-t", *MANDATORY_INDIVIDUAL), intermediate=True),
    Variant("predetermined", ("-p", "-t", *MANDATORY_INDIVIDUAL)),
    Variant("swiss", ("-s", "-t", *MANDATORY_INDIVIDUAL)),
    Variant("unrated-1400", ("-u", "1400", "-t", *MANDATORY_INDIVIDUAL)),
    Variant("file-order", ()),
    Variant("check", ("-c", "-t", *TYPICAL)),
    Variant("rank-sorted", ("-r", "-t", *TYPICAL)),
    Variant("helpers", ("-t", *HELPERS)),
)


@dataclass
class Case:
    name: str
    trf: bytes
    rounds: int


@dataclass
class ErrorCase:
    name: str
    args: list[str]
    trf: Optional[bytes]
    exit_code: int
    stderr_contains: str
    stdout: Optional[str] = None


def last_round(trf: bytes) -> int:
    """The highest round number that has a result column in a 001 record."""
    rounds = 0
    for line in trf.decode("latin-1").replace("\r", "\n").split("\n"):
        if line.startswith("001"):
            rounds = max(rounds, max(0, (len(line.rstrip()) - 89) // 10))
    return rounds


def run(args: list[str], cwd: Path) -> tuple[int, bytes, bytes]:
    result = subprocess.run(
        args,
        cwd=cwd,
        capture_output=True,
        timeout=TIMEOUT_SECONDS,
    )
    return result.returncode, result.stdout, result.stderr


def generate(engine: Path, config: Optional[Path], seed: int, work: Path) -> bytes:
    # The engine resolves -o relative to the configuration file, so the file
    # is copied into the work directory and named relatively (as in
    # run_tests.py); a stale output must never be read back.
    output = work / "gen.trf"
    if output.exists():
        output.unlink()
    args = [str(engine), "--dutch", "-g"]
    if config is not None:
        (work / config.name).write_bytes(config.read_bytes())
        args.append(config.name)
    args += ["-o", "gen.trf", "-s", str(seed)]
    rc, stdout, stderr = run(args, work)
    # The engine ends lines with CR; any player record will do as a sanity
    # check that a tournament was written.
    if rc != 0 or not output.exists() or b"001 " not in output.read_bytes():
        raise RuntimeError(
            "generator failed (%d) for %s seed %d: %s"
            % (rc, config, seed, (stdout + stderr).decode(errors="replace"))
        )
    return (work / "gen.trf").read_bytes()


def collect_cases(engine: Path, count: int, work: Path) -> list[Case]:
    cases = []
    for path in sorted((FIXTURES / "samples").glob("*.trf")):
        data = path.read_bytes()
        cases.append(Case("samples/" + path.stem, data, last_round(data)))
    for name, data in tiebreak_inputs.feature_inputs():
        cases.append(Case("features/" + name, data, last_round(data)))
    sources: list[tuple[str, Optional[Path]]] = [("default", None)]
    sources += [
        (path.stem, path) for path in sorted((FIXTURES / "generator").glob("*.cfg"))
    ]
    seen: dict[bytes, str] = {}
    for label, config in sources:
        for seed in range(1, count + 1):
            data = generate(engine, config, seed, work)
            name = "generated/%s-seed-%04d" % (label, seed)
            # Every source and seed must give its own tournament; a repeat
            # means the generator was not driven as intended.
            if data in seen:
                raise RuntimeError("%s is identical to %s" % (name, seen[data]))
            seen[data] = name
            cases.append(Case(name, data, last_round(data)))
    return cases


def compare(
    case: Case, variant: Variant, tool: Path, gacrux: Path
) -> Optional[str]:
    with tempfile.TemporaryDirectory(prefix="tbcmp-") as directory:
        work = Path(directory)
        (work / "input.trf").write_bytes(case.trf)
        args = list(variant.args)
        if variant.intermediate:
            if case.rounds < 2:
                return None
            args = ["-n", str(case.rounds - 1)] + args
        reference = run(
            [
                sys.executable,
                str(gacrux / "tiebreakchecker.py"),
                "-i",
                "input.trf",
                "-dT",
                *args,
            ],
            work,
        )
        ours = run([str(tool), "-i", "input.trf", "-d", "T", *args], work)
    stem = case.name.split("/", 1)[1]
    if stem in UNSUPPORTED_INPUTS:
        if reference[0] == 0 or ours[0] == 0:
            pass  # fall through: compare as usual, the reason may be gone
        else:
            return None
    # Deliberate difference: a failed -c check exits 1 here, while
    # tiebreakchecker exits 0 and reports it only in its JSON status.
    expected_exit = reference[0]
    if expected_exit == 0 and b"Check: False" in reference[1]:
        expected_exit = 1
    if expected_exit == ours[0] and reference[1] == ours[1]:
        return None
    return (
        "exit gacrux %d, ours %d\n--- gacrux stdout\n%s\n--- ours stdout\n%s"
        "\n--- gacrux stderr\n%s\n--- ours stderr\n%s"
        % (
            reference[0],
            ours[0],
            reference[1].decode("latin-1")[:3000],
            ours[1].decode("latin-1")[:3000],
            reference[2].decode("latin-1")[-1500:],
            ours[2].decode("latin-1")[-1500:],
        )
    )


SIMPLE_TRF = (
    b"012 Error case tournament\n"
    b"001    1      Alpha, A                          2100                             1.0    1     2 w 1  \n"
    b"001    2      Beta, B                           2000                             0.0    2     1 b 0  \n"
)


